interface LanguageState {
  language: Language;
  isLoaded: boolean;
  updateCounter: number;
  setLanguage: (language: Language) => void;
  loadLanguage: () => Promise<void>;
  t: (key: keyof typeof TRANSLATIONS.cs, params?: Record<string, string | number>) => string;
}

export const useLanguageStore = create<LanguageState>((set, get) => ({
  language: 'cs',
  isLoaded: false,
  updateCounter: 0,

  setLanguage: (language: Language) => {
    console.log('Setting language to:', language);
    AsyncStorage.setItem('language', language).then(() => {
      console.log('Language saved successfully:', language);
      // Force re-render by updating counter and language together
      set({ 
        language, 
        isLoaded: true, 
        updateCounter: get().updateCounter + 1 
      });
    }).catch((error) => {
      console.error('Failed to save language:', error);
    });
  },

  loadLanguage: async () => {
    try {
      const savedLanguage = await AsyncStorage.getItem('language');
      let language: Language = 'cs';
      
      if (savedLanguage) {
        // Validate that the saved language is a valid Language type
        if (savedLanguage === 'cs' || savedLanguage === 'en') {
          language = savedLanguage as Language;
        } else {
          console.warn('Invalid language in storage:', savedLanguage, 'defaulting to cs');
          await AsyncStorage.removeItem('language');
        }
      }
      
      console.log('Loading language:', language, 'from storage:', savedLanguage);
      set({ language, isLoaded: true, updateCounter: 0 });
    } catch (error) {
      console.error('Failed to load language:', error);
      // Clear potentially corrupted language data
      try {
        await AsyncStorage.removeItem('language');
      } catch (clearError) {
        console.error('Failed to clear language data:', clearError);
      }
      set({ language: 'cs', isLoaded: true, updateCounter: 0 });
    }
  },

  t: (key: keyof typeof TRANSLATIONS.cs, params?: Record<string, string | number>) => {
    const { language } = get();
    let translation = TRANSLATIONS[language]?.[key] || TRANSLATIONS.cs[key];
    if (!translation) return key;
    if (params) {
      for (const [k, v] of Object.entries(params)) {
        translation = translation.replace(new RegExp(`\\{\\{${k}\\}\\}`, 'g'), String(v));
      }
    }
    return translation;
  },
}));
