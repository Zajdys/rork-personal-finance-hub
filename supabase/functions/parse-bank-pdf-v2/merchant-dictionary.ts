const SORTED = [...MERCHANT_DICTIONARY].sort((a, b) => b.key.length - a.key.length);

/**
 * Najdi kategorii ve slovníku: přesná shoda nebo prefix (ALBERT… → ALBERT).
 * Převod ze slovníku ignorujeme (řeší owner accounts).
 */
export function lookupMerchantDictionary(merchantKey: string): string | null {
  const key = (merchantKey || '').trim().toUpperCase();
  if (!key || key.length < 2) return null;

  for (const entry of SORTED) {
    const k = entry.key.toUpperCase().normalize('NFD').replace(/\p{M}/gu, '');
    if (key === k || key.startsWith(`${k} `) || key.startsWith(k)) {
      if (entry.category === 'Převod') continue;
      return entry.category;
    }
  }
  return null;
}
